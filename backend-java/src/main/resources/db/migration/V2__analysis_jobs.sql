CREATE TABLE analysis_job (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    video_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    generation INT NOT NULL,
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    config_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    config_json JSON NOT NULL,
    status VARCHAR(24) NOT NULL,
    state_version BIGINT NOT NULL DEFAULT 1,
    max_text_calls INT NOT NULL,
    text_calls_reserved INT NOT NULL DEFAULT 0,
    max_asr_submissions INT NOT NULL,
    asr_calls_reserved INT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_job_idempotency (idempotency_key),
    UNIQUE KEY uk_job_generation (video_id, generation),
    KEY idx_job_created (created_at, id),
    CONSTRAINT fk_job_video FOREIGN KEY (video_id) REFERENCES video_asset(id),
    CONSTRAINT ck_job_limits CHECK (generation > 0 AND max_text_calls >= 0 AND text_calls_reserved >= 0 AND max_asr_submissions >= 0 AND asr_calls_reserved >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE job_stage (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_type VARCHAR(16) NOT NULL DEFAULT 'ANALYSIS',
    owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    stage_type VARCHAR(24) NOT NULL,
    shard_key VARCHAR(64) NOT NULL DEFAULT '0',
    status VARCHAR(24) NOT NULL,
    attempt INT NOT NULL DEFAULT 0,
    run_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    worker_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    hard_deadline_at DATETIME(6) NULL,
    next_run_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    input_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    checkpoint_key VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NULL,
    checkpoint_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    manifest_key VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NULL,
    manifest_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    error_code VARCHAR(64) NULL,
    last_retryable BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_stage_identity (job_id, stage_type, shard_key),
    KEY idx_stage_ready (status, next_run_at),
    KEY idx_stage_lease (status, lease_until),
    CONSTRAINT fk_stage_job FOREIGN KEY (job_id) REFERENCES analysis_job(id) ON DELETE CASCADE,
    CONSTRAINT ck_stage_attempt CHECK (attempt >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE stage_claim_request (
    worker_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    claim_request_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    stage_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    attempt INT NULL,
    run_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    outcome VARCHAR(24) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (worker_id, claim_request_id),
    CONSTRAINT fk_claim_stage FOREIGN KEY (stage_id) REFERENCES job_stage(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
