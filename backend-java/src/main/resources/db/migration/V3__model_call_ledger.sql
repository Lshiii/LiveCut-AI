CREATE TABLE model_call (
    request_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    stage_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    operation_key VARCHAR(200) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    input_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    kind VARCHAR(8) NOT NULL,
    status VARCHAR(24) NOT NULL,
    origin_attempt INT NOT NULL,
    origin_token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dispatch_attempt INT NULL,
    dispatch_token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    provider_task_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL,
    response_key VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NULL,
    response_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    usage_json JSON NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (request_id),
    UNIQUE KEY uk_model_operation (stage_id, operation_key),
    KEY idx_model_job (job_id),
    CONSTRAINT fk_model_job FOREIGN KEY (job_id) REFERENCES analysis_job(id) ON DELETE CASCADE,
    CONSTRAINT fk_model_stage FOREIGN KEY (stage_id) REFERENCES job_stage(id) ON DELETE CASCADE,
    CONSTRAINT ck_model_kind CHECK (kind IN ('TEXT', 'ASR')),
    CONSTRAINT ck_model_state CHECK (status IN ('RESERVED', 'DISPATCHING', 'SUBMITTED', 'SUCCEEDED', 'FAILED', 'UNKNOWN_OUTCOME')),
    CONSTRAINT ck_model_attempt CHECK (origin_attempt > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
