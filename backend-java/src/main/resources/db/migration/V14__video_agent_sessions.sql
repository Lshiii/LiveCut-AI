CREATE TABLE agent_session (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    video_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    transcript_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    transcript_key VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    analysis_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    analysis_key VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_json JSON NOT NULL,
    duration_ms BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uk_agent_session_idempotency(idempotency_key),
    KEY idx_agent_session_job(job_id,created_at,id),
    CONSTRAINT fk_agent_session_job FOREIGN KEY(job_id) REFERENCES analysis_job(id) ON DELETE CASCADE,
    CONSTRAINT fk_agent_session_video FOREIGN KEY(video_id) REFERENCES video_asset(id),
    CONSTRAINT ck_agent_session_duration CHECK(duration_ms>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE agent_turn (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    sequence_number INT NOT NULL,
    question TEXT NOT NULL,
    idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    text_model_id VARCHAR(128) NOT NULL,
    text_fallback_models_json JSON NOT NULL,
    max_text_calls INT NOT NULL,
    text_calls_reserved INT NOT NULL DEFAULT 0,
    history_json JSON NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    state_version BIGINT NOT NULL DEFAULT 1,
    result_json JSON NULL,
    result_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uk_agent_turn_idempotency(idempotency_key),
    UNIQUE KEY uk_agent_turn_sequence(session_id,sequence_number),
    KEY idx_agent_turn_owner(job_id,session_id,status,id),
    CONSTRAINT fk_agent_turn_session FOREIGN KEY(session_id) REFERENCES agent_session(id) ON DELETE CASCADE,
    CONSTRAINT fk_agent_turn_job FOREIGN KEY(job_id) REFERENCES analysis_job(id) ON DELETE CASCADE,
    CONSTRAINT ck_agent_turn_limits CHECK(sequence_number BETWEEN 1 AND 100 AND max_text_calls BETWEEN 1 AND 24 AND text_calls_reserved>=0 AND text_calls_reserved<=max_text_calls)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
