package io.livecut.downloads;

import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

import org.springframework.http.CacheControl;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import tools.jackson.databind.json.JsonMapper;

/** Serialize a public document once; the hash describes the exact attachment bytes. */
public final class JsonAttachment {
    private static final JsonMapper JSON = JsonMapper.builder().build();
    private JsonAttachment() {}

    public static ResponseEntity<byte[]> response(String filename, Object document) {
        if (filename == null || !filename.matches("[a-z0-9-]{1,150}\\.json")) {
            throw new IllegalArgumentException("Attachment filename must be generated by the service");
        }
        byte[] bytes = JSON.writeValueAsBytes(document);
        String hash;
        try { hash = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)); }
        catch (NoSuchAlgorithmException unavailable) { throw new IllegalStateException(unavailable); }
        return ResponseEntity.ok().contentType(MediaType.APPLICATION_JSON)
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"" + filename + "\"")
                .header("X-Content-Type-Options", "nosniff")
                .cacheControl(CacheControl.noStore()).eTag("\"" + hash + "\"")
                .contentLength(bytes.length).body(bytes);
    }
}
